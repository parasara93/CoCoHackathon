-- =============================================================================
-- 3. METRIC BOUNDS
-- =============================================================================

-- 3a. FULFILLMENT_PCT between 0 and 100
SELECT 'FULFILLMENT_PCT_BOUNDS' AS check_name,
  SUM(CASE WHEN FULFILLMENT_PCT < 0 OR FULFILLMENT_PCT > 100 THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN FULFILLMENT_PCT < 0 OR FULFILLMENT_PCT > 100 THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT
WHERE FULFILLMENT_PCT IS NOT NULL;

-- 3b. OUTSTANDING_QTY >= 0
SELECT 'OUTSTANDING_QTY_GE_0' AS check_name,
  SUM(CASE WHEN OUTSTANDING_QTY < 0 THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN OUTSTANDING_QTY < 0 THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- 3c. OVER_SHIPPED_QTY >= 0
SELECT 'OVER_SHIPPED_QTY_GE_0' AS check_name,
  SUM(CASE WHEN OVER_SHIPPED_QTY < 0 THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN OVER_SHIPPED_QTY < 0 THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- 3d. EFFECTIVE_SHIPPED_QTY <= ACTIVE_ORDERED_QTY
SELECT 'EFFECTIVE_LE_ACTIVE_ORDERED' AS check_name,
  SUM(CASE WHEN EFFECTIVE_SHIPPED_QTY > ACTIVE_ORDERED_QTY THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN EFFECTIVE_SHIPPED_QTY > ACTIVE_ORDERED_QTY THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
