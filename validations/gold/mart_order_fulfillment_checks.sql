   WHERE m.CUSTOMER_ID IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM SUPPLY_CHAIN_DW.SILVER.DIM_CUSTOMER dc WHERE dc.CUSTOMER_ID = m.CUSTOMER_ID)
  ) = 0 THEN 'PASS' ELSE 'FAIL' END AS result;

-- 2b. FK: PLANT_ID
SELECT 'FK_PLANT_ID' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT m
   WHERE m.PLANT_ID IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM SUPPLY_CHAIN_DW.SILVER.DIM_PLANT dp WHERE dp.PLANT_ID = m.PLANT_ID)
