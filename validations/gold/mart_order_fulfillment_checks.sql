-- =============================================================================
-- 4. FLAG CONSISTENCY
-- =============================================================================

-- 4a. HAS_OVER_SHIPMENT = (OVER_SHIPPED_QTY > 0)
SELECT 'HAS_OVER_SHIPMENT_CONSISTENCY' AS check_name,
  SUM(CASE WHEN HAS_OVER_SHIPMENT != (OVER_SHIPPED_QTY > 0) THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN HAS_OVER_SHIPMENT != (OVER_SHIPPED_QTY > 0) THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- 4b. FULFILLED implies OUTSTANDING_QTY = 0
SELECT 'FULFILLED_IMPLIES_OQ_ZERO' AS check_name,
  SUM(CASE WHEN IS_FULFILLED AND OUTSTANDING_QTY != 0 THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN IS_FULFILLED AND OUTSTANDING_QTY != 0 THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- 4c. PARTIALLY_FULFILLED implies OQ > 0 AND ESQ > 0
SELECT 'PARTIAL_IMPLIES_OQ_AND_ESQ' AS check_name,
  SUM(CASE WHEN IS_PARTIALLY_FULFILLED
    AND NOT (OUTSTANDING_QTY > 0 AND EFFECTIVE_SHIPPED_QTY > 0)
  THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN IS_PARTIALLY_FULFILLED
    AND NOT (OUTSTANDING_QTY > 0 AND EFFECTIVE_SHIPPED_QTY > 0)
  THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- 4d. UNFULFILLED implies OQ > 0 AND ESQ = 0
SELECT 'UNFULFILLED_IMPLIES_OQ_AND_ESQ_ZERO' AS check_name,
  SUM(CASE WHEN IS_UNFULFILLED
    AND NOT (OUTSTANDING_QTY > 0 AND EFFECTIVE_SHIPPED_QTY = 0)
  THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN IS_UNFULFILLED
    AND NOT (OUTSTANDING_QTY > 0 AND EFFECTIVE_SHIPPED_QTY = 0)
  THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- 4e. CANCELLED implies all lines cancelled
SELECT 'CANCELLED_IMPLIES_ALL_LINES' AS check_name,
  SUM(CASE WHEN IS_CANCELLED AND CANCELLED_LINE_COUNT != TOTAL_ORDER_LINE_COUNT THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN IS_CANCELLED AND CANCELLED_LINE_COUNT != TOTAL_ORDER_LINE_COUNT THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- 4f. Exactly one fulfillment state TRUE per row
SELECT 'EXACTLY_ONE_STATE' AS check_name,
  SUM(CASE WHEN (IS_FULFILLED::INT + IS_PARTIALLY_FULFILLED::INT + IS_UNFULFILLED::INT + IS_CANCELLED::INT) != 1
  THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN (IS_FULFILLED::INT + IS_PARTIALLY_FULFILLED::INT + IS_UNFULFILLED::INT + IS_CANCELLED::INT) != 1
  THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- 4g. IS_LATE = IS_CURRENT_LATE OR IS_DELIVERED_LATE
SELECT 'IS_LATE_CONSISTENCY' AS check_name,
  SUM(CASE WHEN IS_LATE != (IS_CURRENT_LATE OR IS_DELIVERED_LATE) THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN IS_LATE != (IS_CURRENT_LATE OR IS_DELIVERED_LATE) THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- 4h. IS_CURRENT_LATE / IS_DELIVERED_LATE overlap count (INFORMATIONAL — not a failure)
SELECT 'LATE_OVERLAP_COUNT' AS check_name,
  SUM(CASE WHEN IS_CURRENT_LATE AND IS_DELIVERED_LATE THEN 1 ELSE 0 END) AS overlap_count,
  'INFORMATIONAL' AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT;

-- =============================================================================
-- 5. RECONCILIATION
-- =============================================================================

-- 5a. RAW_SHIPPED_QTY reconciliation with source
-- mart RAW_SHIPPED_QTY should equal sum of FACT_SHIPMENT_LINE.SHIPPED_QTY
-- for non-cancelled order lines.
SELECT 'RAW_SHIPPED_QTY_RECONCILE' AS check_name,
  (SELECT SUM(RAW_SHIPPED_QTY) FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT) AS mart_total,
  (SELECT SUM(fsl.SHIPPED_QTY)
   FROM SUPPLY_CHAIN_DW.SILVER.FACT_SHIPMENT_LINE fsl
   JOIN SUPPLY_CHAIN_DW.SILVER.FACT_ORDER_LINE fol ON fsl.ORDER_LINE_ID = fol.ORDER_LINE_ID
   WHERE fol.LINE_STATUS != 'CANCELLED') AS source_total,
  CASE WHEN (SELECT SUM(RAW_SHIPPED_QTY) FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT) =
       (SELECT SUM(fsl.SHIPPED_QTY)
        FROM SUPPLY_CHAIN_DW.SILVER.FACT_SHIPMENT_LINE fsl
        JOIN SUPPLY_CHAIN_DW.SILVER.FACT_ORDER_LINE fol ON fsl.ORDER_LINE_ID = fol.ORDER_LINE_ID
        WHERE fol.LINE_STATUS != 'CANCELLED')
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- 5b. ORDER_VALUE reconciliation
SELECT 'ORDER_VALUE_RECONCILE' AS check_name,
  (SELECT SUM(ORDER_VALUE) FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT) AS mart_total,
  (SELECT SUM(LINE_AMOUNT) FROM SUPPLY_CHAIN_DW.SILVER.FACT_ORDER_LINE) AS source_total,
  CASE WHEN (SELECT SUM(ORDER_VALUE) FROM SUPPLY_CHAIN_DW.GOLD.MART_ORDER_FULFILLMENT) =
       (SELECT SUM(LINE_AMOUNT) FROM SUPPLY_CHAIN_DW.SILVER.FACT_ORDER_LINE)
  THEN 'PASS' ELSE 'FAIL' END AS result;

