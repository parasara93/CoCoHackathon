-- 1a. Row count
SELECT 'ROW_COUNT' AS check_name,
  COUNT(*) AS actual, 2250 AS expected,
  CASE WHEN COUNT(*) = 2250 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK;

-- 1b. Column count
SELECT 'COLUMN_COUNT' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.INFORMATION_SCHEMA.COLUMNS
   WHERE TABLE_SCHEMA = 'GOLD' AND TABLE_NAME = 'MART_INVENTORY_RISK') AS actual,
  24 AS expected,
  CASE WHEN (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.INFORMATION_SCHEMA.COLUMNS
   WHERE TABLE_SCHEMA = 'GOLD' AND TABLE_NAME = 'MART_INVENTORY_RISK') = 24
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- 1c. Grain uniqueness
SELECT 'GRAIN_UNIQUENESS' AS check_name,
  (SELECT COUNT(*) FROM (
    SELECT PLANT_ID, PART_ID FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK
    GROUP BY PLANT_ID, PART_ID HAVING COUNT(*) > 1)) AS actual,
  0 AS expected,
  CASE WHEN (SELECT COUNT(*) FROM (
    SELECT PLANT_ID, PART_ID FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK
    GROUP BY PLANT_ID, PART_ID HAVING COUNT(*) > 1)) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- 1d. Null PLANT_ID
SELECT 'NULL_PLANT_ID' AS check_name,
