  CASE WHEN (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK WHERE PART_ID IS NULL) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- 1f. Analysis date
SELECT 'ANALYSIS_AS_OF_DATE' AS check_name,
  NULL AS actual, NULL AS expected,
