-- =============================================================================
-- 3. SOURCE PRESERVATION
-- =============================================================================

-- 3a. NEEDS_REORDER count
SELECT 'NEEDS_REORDER_PRESERVATION' AS check_name,
  (SELECT SUM(CASE WHEN NEEDS_REORDER THEN 1 ELSE 0 END) FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK) AS mart_count,
  (SELECT SUM(CASE WHEN NEEDS_REORDER THEN 1 ELSE 0 END) FROM SUPPLY_CHAIN_DW.SILVER.FACT_INVENTORY_SNAPSHOT) AS source_count,
  CASE WHEN (SELECT SUM(CASE WHEN NEEDS_REORDER THEN 1 ELSE 0 END) FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK) =
       (SELECT SUM(CASE WHEN NEEDS_REORDER THEN 1 ELSE 0 END) FROM SUPPLY_CHAIN_DW.SILVER.FACT_INVENTORY_SNAPSHOT)
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- 3b. BELOW_SAFETY_STOCK count
SELECT 'BELOW_SAFETY_PRESERVATION' AS check_name,
  (SELECT SUM(CASE WHEN BELOW_SAFETY_STOCK THEN 1 ELSE 0 END) FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK) AS mart_count,
  (SELECT SUM(CASE WHEN BELOW_SAFETY_STOCK THEN 1 ELSE 0 END) FROM SUPPLY_CHAIN_DW.SILVER.FACT_INVENTORY_SNAPSHOT) AS source_count,
  CASE WHEN (SELECT SUM(CASE WHEN BELOW_SAFETY_STOCK THEN 1 ELSE 0 END) FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK) =
       (SELECT SUM(CASE WHEN BELOW_SAFETY_STOCK THEN 1 ELSE 0 END) FROM SUPPLY_CHAIN_DW.SILVER.FACT_INVENTORY_SNAPSHOT)
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- 3c. ON_HAND_QTY reconciliation
