-- =============================================================================
-- 2. REFERENTIAL INTEGRITY
-- =============================================================================

-- 2a. FK: PLANT_ID
SELECT 'FK_PLANT_ID' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK m
   WHERE m.PLANT_ID IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM SUPPLY_CHAIN_DW.SILVER.DIM_PLANT dp WHERE dp.PLANT_ID = m.PLANT_ID)
  ) AS actual,
  0 AS expected,
  CASE WHEN (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK m
   WHERE m.PLANT_ID IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM SUPPLY_CHAIN_DW.SILVER.DIM_PLANT dp WHERE dp.PLANT_ID = m.PLANT_ID)
  ) = 0 THEN 'PASS' ELSE 'FAIL' END AS result;

-- 2b. FK: PART_ID
SELECT 'FK_PART_ID' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK m
   WHERE m.PART_ID IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM SUPPLY_CHAIN_DW.SILVER.DIM_PART dpt WHERE dpt.PART_ID = m.PART_ID)
  ) AS actual,
  0 AS expected,
  CASE WHEN (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.GOLD.MART_INVENTORY_RISK m
