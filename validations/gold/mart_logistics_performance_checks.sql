-- 16. Event counts non-negative
SELECT 'Event counts non-negative' AS check_name,
       SUM(CASE WHEN ROUTE_DEVIATION_EVENT_COUNT < 0 OR DELAY_REPORTED_EVENT_COUNT < 0 THEN 1 ELSE 0 END) AS violations,
       CASE WHEN SUM(CASE WHEN ROUTE_DEVIATION_EVENT_COUNT < 0 OR DELAY_REPORTED_EVENT_COUNT < 0 THEN 1 ELSE 0 END) = 0
            THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_LOGISTICS_PERFORMANCE;

-- 17. DISTINCT_ORDER_COUNT non-negative
SELECT 'DISTINCT_ORDER_COUNT non-negative' AS check_name,
       SUM(CASE WHEN DISTINCT_ORDER_COUNT < 0 THEN 1 ELSE 0 END) AS violations,
       CASE WHEN SUM(CASE WHEN DISTINCT_ORDER_COUNT < 0 THEN 1 ELSE 0 END) = 0
            THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_LOGISTICS_PERFORMANCE;

-- 18. SHIPPING_COST reconciles to Silver
SELECT 'SHIPPING_COST matches Silver' AS check_name,
       SUM(CASE WHEN COALESCE(m.SHIPPING_COST, -1) != COALESCE(s.SHIPPING_COST, -1) THEN 1 ELSE 0 END) AS mismatches,
       CASE WHEN SUM(CASE WHEN COALESCE(m.SHIPPING_COST, -1) != COALESCE(s.SHIPPING_COST, -1) THEN 1 ELSE 0 END) = 0
            THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_LOGISTICS_PERFORMANCE m
