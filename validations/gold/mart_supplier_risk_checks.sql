-- =============================================================================
-- MART_SUPPLIER_RISK — Production Validation Checks
-- Target: SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK
-- Run after V2.4.0 is applied.
-- =============================================================================

-- V2.4.0 column contract: 50 columns, 75 rows, grain SUPPLIER_ID

-- =============================================================================
-- 1. STRUCTURAL CHECKS
-- =============================================================================

-- 1a. Row count
SELECT 'ROW_COUNT' AS check_name,
  COUNT(*) AS actual, 75 AS expected,
  CASE WHEN COUNT(*) = 75 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK;

-- 1b. Column count
SELECT 'COLUMN_COUNT' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.INFORMATION_SCHEMA.COLUMNS
   WHERE TABLE_SCHEMA = 'GOLD' AND TABLE_NAME = 'MART_SUPPLIER_RISK') AS actual,
  50 AS expected,
  CASE WHEN (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.INFORMATION_SCHEMA.COLUMNS
   WHERE TABLE_SCHEMA = 'GOLD' AND TABLE_NAME = 'MART_SUPPLIER_RISK') = 50
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- 1c. Grain uniqueness
SELECT 'GRAIN_UNIQUENESS' AS check_name,
  (SELECT COUNT(*) FROM (
    SELECT SUPPLIER_ID FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK
    GROUP BY SUPPLIER_ID HAVING COUNT(*) > 1)) AS actual,
  0 AS expected,
  CASE WHEN (SELECT COUNT(*) FROM (
    SELECT SUPPLIER_ID FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK
    GROUP BY SUPPLIER_ID HAVING COUNT(*) > 1)) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- 1d. Null PK
SELECT 'NULL_SUPPLIER_ID' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK WHERE SUPPLIER_ID IS NULL) AS actual,
  0 AS expected,
  CASE WHEN (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK WHERE SUPPLIER_ID IS NULL) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- 1e. Analysis date
SELECT 'ANALYSIS_AS_OF_DATE' AS check_name,
  NULL AS actual, NULL AS expected,
  CASE WHEN (SELECT COUNT(DISTINCT ANALYSIS_AS_OF_DATE) FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK) = 1
       AND (SELECT MIN(ANALYSIS_AS_OF_DATE) FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK) = '2026-09-30'
  THEN 'PASS' ELSE 'FAIL' END AS result;

-- =============================================================================
-- 2. SEVERITY METRIC BOUNDS (V2.4.0 additions)
-- =============================================================================

-- 2a. OUTSTANDING_EXPOSURE_PCT between 0 and 100
