  0 AS expected,
  CASE WHEN SUM(CASE WHEN OUTSTANDING_EXPOSURE_PCT < 0 OR OUTSTANDING_EXPOSURE_PCT > 100 THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK;

-- 2b. LOW_INVENTORY_EXPOSURE_PCT between 0 and 100
SELECT 'LOW_INV_EXPOSURE_PCT_BOUNDS' AS check_name,
  SUM(CASE WHEN LOW_INVENTORY_EXPOSURE_PCT < 0 OR LOW_INVENTORY_EXPOSURE_PCT > 100 THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN LOW_INVENTORY_EXPOSURE_PCT < 0 OR LOW_INVENTORY_EXPOSURE_PCT > 100 THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK;

-- 2c. LOW_INVENTORY_POSITION_COUNT <= EXPOSED_INVENTORY_POSITION_COUNT
SELECT 'LOW_INV_LE_TOTAL_INV' AS check_name,
  SUM(CASE WHEN LOW_INVENTORY_POSITION_COUNT > EXPOSED_INVENTORY_POSITION_COUNT THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN LOW_INVENTORY_POSITION_COUNT > EXPOSED_INVENTORY_POSITION_COUNT THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
