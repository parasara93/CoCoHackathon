           OR LATEST_AVG_LEAD_TIME_DAYS IS NULL OR EARLIEST_AVG_LEAD_TIME_DAYS IS NULL
           OR LATEST_RISK_SCORE IS NULL OR EARLIEST_RISK_SCORE IS NULL
           OR MEASUREMENT_PERIOD_COUNT IS NULL THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN LATEST_ON_TIME_DELIVERY_PCT IS NULL OR EARLIEST_ON_TIME_DELIVERY_PCT IS NULL
           OR LATEST_QUALITY_SCORE IS NULL OR EARLIEST_QUALITY_SCORE IS NULL
           OR LATEST_AVG_LEAD_TIME_DAYS IS NULL OR EARLIEST_AVG_LEAD_TIME_DAYS IS NULL
           OR LATEST_RISK_SCORE IS NULL OR EARLIEST_RISK_SCORE IS NULL
           OR MEASUREMENT_PERIOD_COUNT IS NULL THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK;

