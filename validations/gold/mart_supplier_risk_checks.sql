-- =============================================================================
-- 6. SCENARIO 1 (SC-000001) VALIDATION — SEPARATE
-- Run only after VALIDATION.SCENARIO_AFFECTED_ENTITY is loaded.
-- =============================================================================

-- 6a. SUP-000062 flags
SELECT 'SC1_SUP062_FLAGS' AS check_name,
  CASE WHEN IS_SUPPLIER_AT_RISK = TRUE
       AND HAS_SUPPLIER_PERFORMANCE_DETERIORATION = TRUE
       AND HAS_OTD_DETERIORATION = TRUE
       AND HAS_DOWNSTREAM_EXPOSURE = TRUE
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK
WHERE SUPPLIER_ID = 'SUP-000062';

-- 6b. Part coverage (ID-set comparison)
SELECT 'SC1_PARTS' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.VALIDATION.SCENARIO_AFFECTED_ENTITY
   WHERE SCENARIO_ID = 'SC-000001' AND ENTITY_TYPE = 'PART') AS gt_count,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.SILVER.BRIDGE_SUPPLIER_PART
   WHERE SUPPLIER_ID = 'SUP-000062' AND ACTIVE_FLAG = TRUE) AS mart_count,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.VALIDATION.SCENARIO_AFFECTED_ENTITY gt
   JOIN SUPPLY_CHAIN_DW.SILVER.BRIDGE_SUPPLIER_PART bsp
     ON gt.ENTITY_ID = bsp.PART_ID AND bsp.SUPPLIER_ID = 'SUP-000062' AND bsp.ACTIVE_FLAG = TRUE
   WHERE gt.SCENARIO_ID = 'SC-000001' AND gt.ENTITY_TYPE = 'PART') AS matched;

-- 6c. Plant coverage
SELECT 'SC1_PLANTS' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.VALIDATION.SCENARIO_AFFECTED_ENTITY
   WHERE SCENARIO_ID = 'SC-000001' AND ENTITY_TYPE = 'PLANT') AS gt_count,
  (SELECT COUNT(DISTINCT inv.PLANT_ID)
   FROM SUPPLY_CHAIN_DW.SILVER.BRIDGE_SUPPLIER_PART bsp
   JOIN SUPPLY_CHAIN_DW.SILVER.FACT_INVENTORY_SNAPSHOT inv ON bsp.PART_ID = inv.PART_ID
   WHERE bsp.SUPPLIER_ID = 'SUP-000062' AND bsp.ACTIVE_FLAG = TRUE) AS mart_count,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.VALIDATION.SCENARIO_AFFECTED_ENTITY gt
   WHERE gt.SCENARIO_ID = 'SC-000001' AND gt.ENTITY_TYPE = 'PLANT'
     AND EXISTS (SELECT 1 FROM SUPPLY_CHAIN_DW.SILVER.BRIDGE_SUPPLIER_PART bsp
                 JOIN SUPPLY_CHAIN_DW.SILVER.FACT_INVENTORY_SNAPSHOT inv ON bsp.PART_ID = inv.PART_ID
                 WHERE bsp.SUPPLIER_ID = 'SUP-000062' AND bsp.ACTIVE_FLAG = TRUE
                   AND inv.PLANT_ID = gt.ENTITY_ID)) AS matched;

-- 6d. Shipment coverage
SELECT 'SC1_SHIPMENTS' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.VALIDATION.SCENARIO_AFFECTED_ENTITY
   WHERE SCENARIO_ID = 'SC-000001' AND ENTITY_TYPE = 'SHIPMENT') AS gt_count,
  (SELECT COUNT(DISTINCT sl.SHIPMENT_ID)
   FROM SUPPLY_CHAIN_DW.SILVER.BRIDGE_SUPPLIER_PART bsp
   JOIN SUPPLY_CHAIN_DW.SILVER.FACT_SHIPMENT_LINE sl ON bsp.PART_ID = sl.PART_ID
   WHERE bsp.SUPPLIER_ID = 'SUP-000062' AND bsp.ACTIVE_FLAG = TRUE) AS mart_count,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.VALIDATION.SCENARIO_AFFECTED_ENTITY gt
   WHERE gt.SCENARIO_ID = 'SC-000001' AND gt.ENTITY_TYPE = 'SHIPMENT'
     AND EXISTS (SELECT 1 FROM SUPPLY_CHAIN_DW.SILVER.BRIDGE_SUPPLIER_PART bsp
                 JOIN SUPPLY_CHAIN_DW.SILVER.FACT_SHIPMENT_LINE sl ON bsp.PART_ID = sl.PART_ID
                 WHERE bsp.SUPPLIER_ID = 'SUP-000062' AND bsp.ACTIVE_FLAG = TRUE
                   AND sl.SHIPMENT_ID = gt.ENTITY_ID)) AS matched;

-- 6e. Order coverage
SELECT 'SC1_ORDERS' AS check_name,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.VALIDATION.SCENARIO_AFFECTED_ENTITY
   WHERE SCENARIO_ID = 'SC-000001' AND ENTITY_TYPE = 'ORDER') AS gt_count,
  (SELECT COUNT(DISTINCT ol.ORDER_ID)
   FROM SUPPLY_CHAIN_DW.SILVER.BRIDGE_SUPPLIER_PART bsp
   JOIN SUPPLY_CHAIN_DW.SILVER.FACT_ORDER_LINE ol ON bsp.PART_ID = ol.PART_ID
   WHERE bsp.SUPPLIER_ID = 'SUP-000062' AND bsp.ACTIVE_FLAG = TRUE
     AND ol.LINE_STATUS != 'CANCELLED') AS mart_count,
  (SELECT COUNT(*) FROM SUPPLY_CHAIN_DW.VALIDATION.SCENARIO_AFFECTED_ENTITY gt
   WHERE gt.SCENARIO_ID = 'SC-000001' AND gt.ENTITY_TYPE = 'ORDER'
     AND EXISTS (SELECT 1 FROM SUPPLY_CHAIN_DW.SILVER.BRIDGE_SUPPLIER_PART bsp
                 JOIN SUPPLY_CHAIN_DW.SILVER.FACT_ORDER_LINE ol ON bsp.PART_ID = ol.PART_ID
                 WHERE bsp.SUPPLIER_ID = 'SUP-000062' AND bsp.ACTIVE_FLAG = TRUE
                   AND ol.LINE_STATUS != 'CANCELLED'
                   AND ol.ORDER_ID = gt.ENTITY_ID)) AS matched;
