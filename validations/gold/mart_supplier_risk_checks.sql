-- 2d. ACTIVE_EXPOSED_OUTSTANDING_VALUE <= ACTIVE_EXPOSED_ORDER_VALUE
SELECT 'ACTIVE_OUTSTANDING_LE_ACTIVE_ORDER' AS check_name,
  SUM(CASE WHEN ACTIVE_EXPOSED_OUTSTANDING_VALUE > ACTIVE_EXPOSED_ORDER_VALUE THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN ACTIVE_EXPOSED_OUTSTANDING_VALUE > ACTIVE_EXPOSED_ORDER_VALUE THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK;

-- =============================================================================
-- 3. FLAG CONSISTENCY
-- =============================================================================

-- 3a. HAS_SUPPLIER_PERFORMANCE_DETERIORATION
SELECT 'PERF_DETERIORATION_CONSISTENCY' AS check_name,
  SUM(CASE WHEN HAS_SUPPLIER_PERFORMANCE_DETERIORATION !=
    (HAS_OTD_DETERIORATION OR HAS_QUALITY_DETERIORATION OR HAS_LEAD_TIME_DETERIORATION)
  THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN HAS_SUPPLIER_PERFORMANCE_DETERIORATION !=
    (HAS_OTD_DETERIORATION OR HAS_QUALITY_DETERIORATION OR HAS_LEAD_TIME_DETERIORATION)
  THEN 1 ELSE 0 END) = 0 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK;

-- 3b. HAS_DOWNSTREAM_EXPOSURE
SELECT 'DOWNSTREAM_EXPOSURE_CONSISTENCY' AS check_name,
  SUM(CASE WHEN HAS_DOWNSTREAM_EXPOSURE !=
    (HAS_LATE_SHIPMENT_EXPOSURE OR HAS_OUTSTANDING_ORDER_EXPOSURE OR HAS_LOW_INVENTORY_EXPOSURE)
  THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN HAS_DOWNSTREAM_EXPOSURE !=
    (HAS_LATE_SHIPMENT_EXPOSURE OR HAS_OUTSTANDING_ORDER_EXPOSURE OR HAS_LOW_INVENTORY_EXPOSURE)
  THEN 1 ELSE 0 END) = 0 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK;

-- 3c. IS_SUPPLIER_AT_RISK
SELECT 'AT_RISK_CONSISTENCY' AS check_name,
  SUM(CASE WHEN IS_SUPPLIER_AT_RISK !=
    (HAS_SUPPLIER_PERFORMANCE_DETERIORATION AND HAS_DOWNSTREAM_EXPOSURE)
  THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN IS_SUPPLIER_AT_RISK !=
    (HAS_SUPPLIER_PERFORMANCE_DETERIORATION AND HAS_DOWNSTREAM_EXPOSURE)
  THEN 1 ELSE 0 END) = 0 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK;

-- 3d. HAS_LOW_INVENTORY_EXPOSURE = (LOW_INVENTORY_POSITION_COUNT > 0)
SELECT 'LOW_INV_FLAG_CONSISTENCY' AS check_name,
  SUM(CASE WHEN HAS_LOW_INVENTORY_EXPOSURE != (LOW_INVENTORY_POSITION_COUNT > 0) THEN 1 ELSE 0 END) AS actual,
  0 AS expected,
  CASE WHEN SUM(CASE WHEN HAS_LOW_INVENTORY_EXPOSURE != (LOW_INVENTORY_POSITION_COUNT > 0) THEN 1 ELSE 0 END) = 0
  THEN 'PASS' ELSE 'FAIL' END AS result
FROM SUPPLY_CHAIN_DW.GOLD.MART_SUPPLIER_RISK;

-- =============================================================================
-- 4. PERFORMANCE COMPLETENESS
-- =============================================================================

SELECT 'PERF_NULL_CHECK' AS check_name,
